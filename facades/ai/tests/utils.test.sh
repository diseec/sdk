#!/bin/bash

# Test for AI utility functions

# Test token counting function
test_sdk_fac_ai_count_tokens() {
    local test_text="This is a test sentence with multiple words."
    
    local token_count
    token_count=$(d ai function sdk_fac_ai_count_tokens "$test_text")
    
    # Should return a reasonable token count (more than 0, less than word count * 2)
    local word_count=$(echo "$test_text" | wc -w | tr -d ' ')
    
    assert_not_equals "0" "$token_count" "Token count should be greater than 0"
    
    # Token count should be reasonable (between words and words * 2)
    local max_expected=$((word_count * 2))
    
    # Use arithmetic comparison
    if [ "$token_count" -gt 0 ] && [ "$token_count" -le "$max_expected" ]; then
        assert_equals "0" "0" "Token count should be in reasonable range"
    else
        assert_equals "reasonable_range" "$token_count" "Token count $token_count should be between 1 and $max_expected"
    fi
}

# Test JSON escaping function
test_sdk_fac_ai_escape_json() {
    local test_text='This has "quotes" and \backslashes and
newlines'
    
    local escaped
    escaped=$(d ai function sdk_fac_ai_escape_json "$test_text")
    
    # Should escape quotes
    assert_contains "$escaped" '\\"' "Should escape double quotes"
    
    # Should escape backslashes
    assert_contains "$escaped" '\\\\' "Should escape backslashes"
    
    # Should escape newlines
    assert_contains "$escaped" '\\n' "Should escape newlines"
}

# Test fallback commit message function
test_sdk_fac_ai_fallback_commit_message() {
    local files_changed="file1.txt
file2.js
file3.md"
    
    local message
    message=$(d ai function sdk_fac_ai_fallback_commit_message "$files_changed")
    
    # Should contain indication of multiple files
    assert_contains "$message" "3 files\|Update.*files" "Should indicate multiple files updated"
    
    # Should contain file names
    assert_contains "$message" "file1.txt" "Should mention first file"
}

# Test large autogenerated file detection
test_sdk_fac_ai_is_large_autogenerated_file() {
    # Create test files
    local lockfile="$TEST_WORKSPACE/package-lock.json"
    local normalfile="$TEST_WORKSPACE/regular.js"
    
    echo "test content" > "$normalfile"
    echo '{"name": "test", "lockfileVersion": 1}' > "$lockfile"
    
    # Test lockfile detection
    d ai function sdk_fac_ai_is_large_autogenerated_file "$lockfile"
    local lockfile_result=$?
    assert_equals "0" "$lockfile_result" "Should detect package-lock.json as autogenerated"
    
    # Test normal file
    d ai function sdk_fac_ai_is_large_autogenerated_file "$normalfile"
    local normalfile_result=$?
    assert_not_equals "0" "$normalfile_result" "Should not detect regular.js as autogenerated"
}

# Test prompt loading function
test_sdk_fac_ai_prompt_load() {
    # Test loading a built-in prompt (if it exists)
    local prompt_content
    prompt_content=$(d ai function sdk_fac_ai_prompt_load "commit" 2>/dev/null)
    local result=$?
    
    if [ "$result" -eq 0 ]; then
        # If prompt loaded successfully, it should have content
        assert_not_empty "$prompt_content" "Loaded prompt should have content"
        assert_contains "$prompt_content" "commit\|changes\|Generate" "Commit prompt should contain relevant terms"
    else
        # If prompt doesn't exist, function should fail gracefully
        assert_not_equals "0" "$result" "Function should fail for non-existent prompt"
    fi
}

# Test prompt placeholder replacement
test_sdk_fac_ai_prompt_replace_placeholders() {
    local template="Hello {{NAME}}, your {{TYPE}} is ready."
    
    local result
    result=$(d ai function sdk_fac_ai_prompt_replace_placeholders "$template" "NAME=World" "TYPE=order")
    
    # Should replace placeholders
    assert_contains "$result" "Hello World" "Should replace NAME placeholder"
    assert_contains "$result" "order is ready" "Should replace TYPE placeholder"
    
    # Should not contain unreplaced placeholders
    echo "$result" | grep -F "{{" > /dev/null 2>&1
    local has_placeholders=$?
    assert_not_equals "0" "$has_placeholders" "Should not contain unreplaced placeholders"
}
