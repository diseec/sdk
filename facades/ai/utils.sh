#!/bin/bash
# AI Module Utilities
# Helper functions for data processing and validation

# Escape a string for JSON
# Usage: sdk_fac_ai_escape_json "string to escape"
# Output: JSON-escaped string
sdk_fac_ai_escape_json() {
    local input="$1"
    echo "$input" | sed 's/\\/\\\\/g' | sed 's/"/\\"/g' | tr '\n' '\r' | sed 's/\r/\\n/g'
}

# Extract content from OpenAI API response
# Usage: sdk_fac_ai_extract_response "response_json"
# Output: Extracted content or original response if parsing fails
sdk_fac_ai_extract_response() {
    local response="$1"
    
    # Try jq first (preferred method)
    if command -v _jq >/dev/null 2>&1; then
        echo "$response" | _jq -r '.choices[0].message.content' 2>/dev/null
    else
        # Fallback to grep/sed if jq is not available
        echo "$response" | grep -o '"content":"[^"]*"' | sed 's/"content":"//g' | sed 's/"$//g' | sed 's/\\n/\n/g'
    fi
}

# Count approximate tokens in a text
# Usage: sdk_fac_ai_count_tokens "text"
# Output: Approximate token count
sdk_fac_ai_count_tokens() {
    local text="$1"
    local word_count=$(echo "$text" | wc -w | tr -d ' ')
    
    # Approximate token count (OpenAI uses ~1.3 tokens per word)
    local token_count=$(( word_count * 13 / 10 ))
    echo "$token_count"
}

# Check if OpenAI API response contains an error
# Usage: sdk_fac_ai_has_error "response_json"
# Returns: 0 if error found, 1 if no error
sdk_fac_ai_has_error() {
    local response="$1"
    if echo "$response" | grep -q '"error"'; then
        return 0
    else
        return 1
    fi
}

# Generate fallback commit message when AI is not available
# Usage: sdk_fac_ai_fallback_commit_message "files_changed"
# Output: Simple commit message based on file changes
sdk_fac_ai_fallback_commit_message() {
    local files_changed="$1"
    local num_files=$(echo "$files_changed" | wc -l | tr -d ' ')
    local main_file=$(echo "$files_changed" | head -1)
    
    if [ "$num_files" -eq 1 ]; then
        echo "Update $main_file"
    else
        echo "Update $num_files files"
        echo ""
        echo "Modified files:"
        echo "$files_changed" | sed 's/^/- /'
    fi
}

# Check if a file is likely a large auto-generated file (e.g., lockfile)
# Usage: sdk_fac_ai_is_large_autogenerated_file "filepath"
# Returns: 0 if likely auto-generated, 1 if not
sdk_fac_ai_is_large_autogenerated_file() {
    local filepath="$1"
    local filename=$(basename "$filepath")
    
    # Check file patterns typically associated with auto-generated content
    if [[ "$filename" == *"lock"* ]] || 
       [[ "$filename" == "package-lock.json" ]] || 
       [[ "$filename" == "yarn.lock" ]] || 
       [[ "$filename" == "pnpm-lock.yaml" ]] || 
       [[ "$filename" == ".min."* ]] || 
       [[ "$filename" == *".min.js" ]] || 
       [[ "$filename" == *".min.css" ]] || 
       [[ "$filename" == "dist/"* ]] || 
       [[ "$filename" == "build/"* ]]; then
        return 0
    fi
    
    # Check file size (over 20KB is considered large)
    local file_size=$(stat -f%z "$filepath" 2>/dev/null || stat -c%s "$filepath" 2>/dev/null)
    if [ -n "$file_size" ] && [ "$file_size" -gt 20480 ]; then
        return 0
    fi
    
    return 1
}

# Truncate text to stay within token limit
# Usage: sdk_fac_ai_truncate_to_token_limit "text" "max_tokens"
# Output: Truncated text
sdk_fac_ai_truncate_to_token_limit() {
    local text="$1"
    local max_tokens="${2:-1000}"
    local current_tokens=$(sdk_fac_ai_count_tokens "$text")
    
    if [ "$current_tokens" -le "$max_tokens" ]; then
        # Text is already within limits
        echo "$text"
        return 0
    fi
    
    # Calculate approximate char/token ratio for this text
    local char_count=${#text}
    local chars_per_token=$(( char_count / current_tokens ))
    
    # Calculate target character count with 10% buffer
    local target_char_count=$(( max_tokens * chars_per_token * 9 / 10 ))
    
    # Truncate text (preserving lines by taking first N chars)
    local truncated_text="${text:0:$target_char_count}"
    
    # Add truncation message
    truncated_text+=$'\n\n[Content truncated to fit token limit]'
    
    echo "$truncated_text"
}
