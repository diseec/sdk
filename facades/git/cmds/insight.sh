#!/bin/bash

# Helper function to get today's date range
sdk_fac_git_cmd_get_today_date_range() {
    local today_start=$(date '+%Y-%m-%d 00:00:00')
    local today_end=$(date '+%Y-%m-%d %H:%M:%S')
    local today_date=$(date '+%Y-%m-%d')
    
    echo "$today_start|$today_end|$today_date"
}

sdk_fac_git_cmd_get_today_logs() {
    local date_range=$(sdk_fac_git_cmd_get_today_date_range)
    local today_start=$(echo "$date_range" | cut -d'|' -f1)
    local today_end=$(echo "$date_range" | cut -d'|' -f2)
    
    echo "$(cli_ctx git _ log --since="$today_start" --until="$today_end" --pretty=format:"%h|%s|%an|%ad" --date=short 2>/dev/null)"
}

# Check and handle daily insight cache
sdk_fac_git_cmd_check_daily_cache() {
    local today_date="$1"
    local cache_file="$2"
    
    if [ -f "$cache_file" ]; then
        read -p "Found insight for today $today_date. rewrite? [Y/N]: " cache_choice
        if [[ "$cache_choice" =~ ^[Yy]$ ]]; then
            echo "rewrite"
        else
            echo ""
            echo -e "\033[36m$(cat "$cache_file")\033[0m"
            echo ""
            echo "cached"
        fi
    else
        echo "generate"
    fi
}

# Get git logs for a specific repository
sdk_fac_git_cmd_get_repo_logs() {
    local module_path="$1"
    local repo_path="$2"
    local today_start="$3"
    local today_end="$4"
    
    if [ "$module_path" = "." ]; then
        # For main repository
        cd "$repo_path" && sdk_fac_git_cmd_get_today_logs
    else
        # For submodules - directly use git in the submodule directory
        cd "$repo_path" && $D_CLI_GLOBAL_NAME api v1 git.log.--today
    fi
}

# Get commit diff with large file filtering
sdk_fac_git_cmd_get_filtered_commit_diff() {
    local module_path="$1"
    local repo_path="$2"
    local hash="$3"
    
    local commit_diff=""
    if [ "$module_path" = "." ]; then
        commit_diff=$(cd "$repo_path" && _git show --stat "$hash" 2>/dev/null)
    else
        commit_diff=$(cd "$repo_path" && git show --stat "$hash" 2>/dev/null)
    fi
    
    # Filter out large auto-generated files
    local file_lines=$(echo "$commit_diff" | grep '|' | sed 's/|.*$//' | sed 's/^ *//')
    local has_large_files=false
    
    while IFS= read -r file; do
        if [ -n "$file" ] && [ -f "$repo_path/$file" ] && cli_ctx ai function sdk_fac_ai_is_large_autogenerated_file "$repo_path/$file"; then
            has_large_files=true
            commit_diff=$(echo "$commit_diff" | grep -F -v "$file")
        fi
    done <<< "$file_lines"
    
    if [ "$has_large_files" = true ]; then
        commit_diff+=$'\n[Some large or auto-generated files were excluded]'
    fi
    
    echo "$commit_diff"
}

# Get git status for a repository
sdk_fac_git_cmd_get_repo_status() {
    local module_path="$1"
    local repo_path="$2"
    
    if [ "$module_path" = "." ]; then
        cd "$repo_path" && _git status --porcelain 2>/dev/null
    else
        cd "$repo_path" && git status --porcelain 2>/dev/null
    fi
}

# Get filtered git status (excluding large auto-generated files)
sdk_fac_git_cmd_get_filtered_status() {
    local repo_path="$1"
    local status_output="$2"
    
    local filtered_status=""
    while IFS= read -r line; do
        local file=$(echo "$line" | sed 's/^...//')
        if [ -n "$file" ] && [ -f "$repo_path/$file" ] && ! cli_ctx ai function sdk_fac_ai_is_large_autogenerated_file "$repo_path/$file"; then
            filtered_status+="$line"$'\n'
        fi
    done <<< "$status_output"
    
    echo "$filtered_status"
}

# Get git diffs for uncommitted changes
sdk_fac_git_cmd_get_repo_diffs() {
    local module_path="$1"
    local repo_path="$2"
    
    local unstaged_diff=""
    local staged_diff=""
    
    if [ "$module_path" = "." ]; then
        unstaged_diff=$(cd "$repo_path" && _git diff 2>/dev/null)
        staged_diff=$(cd "$repo_path" && _git diff --staged 2>/dev/null)
    else
        unstaged_diff=$(cd "$repo_path" && git diff 2>/dev/null)
        staged_diff=$(cd "$repo_path" && git diff --staged 2>/dev/null)
    fi
    
    echo "$staged_diff|$unstaged_diff"
}

# Get repository statistics
sdk_fac_git_cmd_get_repo_stats() {
    local module_path="$1"
    local repo_path="$2"
    local today_start="$3"
    local today_end="$4"
    
    if [ "$module_path" = "." ]; then
        cd "$repo_path" && _git log --since="$today_start" --until="$today_end" --numstat 2>/dev/null
    else
        cd "$repo_path" && git log --since="$today_start" --until="$today_end" --numstat 2>/dev/null
    fi
}

# Process commits for a single repository
sdk_fac_git_cmd_process_repo_commits() {
    local module_name="$1"
    local module_path="$2"
    local repo_path="$3"
    local today_start="$4"
    local today_end="$5"
    local -n all_commits_ref="$6"
    local -n commit_list_ref="$7"
    
    local commits=$(sdk_fac_git_cmd_get_repo_logs "$module_path" "$repo_path" "$today_start" "$today_end")
    
    if [ -n "$commits" ]; then
        while IFS='|' read -r hash subject author date; do
            if [ -n "$hash" ]; then
                # Add to commit list for table display
                commit_list_ref+="$module_name: $hash - $subject ($author, $date)"$'\n'
                
                # Get filtered commit diff
                local commit_diff=$(sdk_fac_git_cmd_get_filtered_commit_diff "$module_path" "$repo_path" "$hash")
                
                # Add to all commits data
                all_commits_ref="$all_commits_ref
REPO: $module_name
COMMIT: \"$hash\" - $subject
AUTHOR: $author
DATE: $date
CHANGES:
$commit_diff
---"
            fi
        done <<< "$commits"
    fi
}

# Process uncommitted changes for a single repository
sdk_fac_git_cmd_process_repo_changes() {
    local module_name="$1"
    local module_path="$2"
    local repo_path="$3"
    local -n all_changes_ref="$4"
    
    local status_output=$(sdk_fac_git_cmd_get_repo_status "$module_path" "$repo_path")
    
    if [ -n "$status_output" ]; then
        local filtered_status=$(sdk_fac_git_cmd_get_filtered_status "$repo_path" "$status_output")
        local diffs=$(sdk_fac_git_cmd_get_repo_diffs "$module_path" "$repo_path")
        local staged_diff=$(echo "$diffs" | cut -d'|' -f1)
        local unstaged_diff=$(echo "$diffs" | cut -d'|' -f2)
        
        if [ -n "$unstaged_diff" ] || [ -n "$staged_diff" ]; then
            all_changes_ref="$all_changes_ref
REPO: $module_name - UNCOMMITTED CHANGES
STATUS:
$filtered_status"
            
            if [ -n "$staged_diff" ]; then
                all_changes_ref="$all_changes_ref
STAGED CHANGES:
$staged_diff"
            fi
            
            if [ -n "$unstaged_diff" ]; then
                all_changes_ref="$all_changes_ref
UNSTAGED CHANGES:
$unstaged_diff"
            fi
            
            all_changes_ref="$all_changes_ref
---"
        fi
    fi
}

# Calculate statistics for a single repository
sdk_fac_git_cmd_calculate_repo_stats() {
    local module_path="$1"
    local repo_path="$2"
    local today_start="$3"
    local today_end="$4"
    local -n total_files_changed_ref="$5"
    local -n total_insertions_ref="$6"
    local -n total_deletions_ref="$7"
    
    local repo_stats=$(sdk_fac_git_cmd_get_repo_stats "$module_path" "$repo_path" "$today_start" "$today_end")
    
    if [ -n "$repo_stats" ]; then
        while read -r insertions deletions file; do
            if [[ "$insertions" =~ ^[0-9]+$ ]] && [[ "$deletions" =~ ^[0-9]+$ ]]; then
                total_insertions_ref=$((total_insertions_ref + insertions))
                total_deletions_ref=$((total_deletions_ref + deletions))
                total_files_changed_ref=$((total_files_changed_ref + 1))
            fi
        done <<< "$repo_stats"
    fi
}

# Main function to collect all data for a repository
sdk_fac_git_cmd_collect_repo_data() {
    local module_name="$1"
    local module_path="$2"
    local today_start="$3"
    local today_end="$4"
    local -n all_commits_ref="$5"
    local -n all_changes_ref="$6"
    local -n total_files_changed_ref="$7"
    local -n total_insertions_ref="$8"
    local -n total_deletions_ref="$9"
    local -n commit_list_ref="${10}"
    
    local repo_path="$D_CTX_DIR/$module_path"
    
    # Skip if not a git repository
    if [ ! -d "$repo_path/.git" ] && [ ! -f "$repo_path/.git" ]; then
        return 0
    fi
    
    # Process commits
    sdk_fac_git_cmd_process_repo_commits "$module_name" "$module_path" "$repo_path" "$today_start" "$today_end" all_commits_ref commit_list_ref
    
    # Process uncommitted changes
    sdk_fac_git_cmd_process_repo_changes "$module_name" "$module_path" "$repo_path" all_changes_ref
    
    # Calculate statistics
    sdk_fac_git_cmd_calculate_repo_stats "$module_path" "$repo_path" "$today_start" "$today_end" total_files_changed_ref total_insertions_ref total_deletions_ref
}
    
# Format and display commit table
sdk_fac_git_cmd_display_commit_table() {
    local commit_list="$1"
    local total_files_changed="$2"
    local total_insertions="$3"
    local total_deletions="$4"
    
    echo "The following commits will be included in the daily insight:"
    echo ""
    
    # Column headers
    printf "%-15s %-8s %-50s %-20s %-10s\n" "REPOSITORY" "COMMIT" "MESSAGE" "AUTHOR" "DATE"
    printf "%s\n" "$(printf '=%.0s' {1..110})"
    
    # Process commit list and format as table
    echo "$commit_list" | while IFS= read -r line; do
        if [ -n "$line" ]; then
            # Parse the line with a more reliable approach
            repo=$(echo "$line" | cut -d: -f1)
            rest=$(echo "$line" | cut -d: -f2- | sed 's/^ //')
            
            hash=$(echo "$rest" | awk '{print $1}')
            
            # Extract the commit message more robustly
            message=$(echo "$rest" | sed -E 's/^[^ ]+ - (.+) \([^,]+, [0-9-]+\)$/\1/')
            
            # Truncate message if too long
            if [ ${#message} -gt 47 ]; then
                message="${message:0:44}..."
            fi
            
            # Extract author and date
            author=$(echo "$rest" | sed -E 's/^.+\(([^,]+), ([0-9-]+)\)$/\1/')
            date=$(echo "$rest" | sed -E 's/^.+\(([^,]+), ([0-9-]+)\)$/\2/')
            
            printf "%-15s %-8s %-50s %-20s %-10s\n" "$repo" "$hash" "$message" "$author" "$date"
        fi
    done
    
    echo ""
    echo "Total changes: $total_files_changed files (+$total_insertions -$total_deletions lines)"
    echo ""
}

# Generate and save the insight report
sdk_fac_git_cmd_generate_insight_report() {
    local analysis_data="$1"
    local cache_file="$2"
    local total_files_changed="$3"
    local total_insertions="$4"
    local total_deletions="$5"
    
    if cli_ctx ai function sdk_fac_ai_is_available; then
        echo ""
        logit -a "Writing daily insights..."
        echo ""

        local ai_insight=$(cli_ctx ai function sdk_fac_ai_generate_daily_insight "$analysis_data")
        
        if [ -n "$ai_insight" ]; then
            # Save the result to cache
            {
                echo "Daily Development Report - $(date '+%Y-%m-%d')"
                echo ""
                echo "$ai_insight"
                echo ""
                echo "$total_files_changed files changes (+$total_insertions -$total_deletions lines)"
            } > "$cache_file"
            
            echo "Daily insight report generated and cached"
            echo ""
            echo -e "\033[36m$(cat "$cache_file")\033[0m"
        else
            logit -e "Failed to generate AI insight. Showing raw data."
            echo ""
            echo "$analysis_data"
        fi
    else
        logit -e "AI not available. Showing raw data instead."
        echo ""
        echo "$analysis_data"
    fi
    echo ""
}

sdk_fac_git_cmd_daily_insight() {
    # Get today's date range
    local date_range=$(sdk_fac_git_cmd_get_today_date_range)
    local today_start=$(echo "$date_range" | cut -d'|' -f1)
    local today_end=$(echo "$date_range" | cut -d'|' -f2)
    local today_date=$(echo "$date_range" | cut -d'|' -f3)
    
    local cache_dir=$(cli_ctx config function sdk_fac_con_get_cache_subdir repository "insights")
    local cache_file="$cache_dir/daily_insight_$today_date.txt"

    # Check cache and handle user choice
    local cache_action=$(sdk_fac_git_cmd_check_daily_cache "$today_date" "$cache_file")
    if [ "$cache_action" = "cached" ]; then
        return 0
    fi
    
    echo "Preparing daily insight report for $today_start to $today_end.."
    
    # Initialize data collection variables
    local all_commits=""
    local all_changes=""
    local total_files_changed=0
    local total_insertions=0
    local total_deletions=0
    local commit_list=""
    
    # Wrapper function for collect_repo_data to match expected signature
    collect_repo_data_wrapper() {
        local module_name="$1"
        local module_path="$2"
        sdk_fac_git_cmd_collect_repo_data "$module_name" "$module_path" "$today_start" "$today_end" \
            all_commits all_changes total_files_changed total_insertions total_deletions commit_list
    }
    
    # Process main repository
    collect_repo_data_wrapper "$D_REPO_NAME" "."
    
    # Process all selected submodules
    cli_ctx config function sdk_fac_con_set_act_foreach_selected_module collect_repo_data_wrapper
    
    # Check if any data was collected
    if [ -z "$all_commits" ] && [ -z "$all_changes" ]; then
        logit -i "No commits or changes found for today"
        return 0
    fi
    
    # Display commit table and get user confirmation
    sdk_fac_git_cmd_display_commit_table "$commit_list" "$total_files_changed" "$total_insertions" "$total_deletions"
    
    read -p "Generate daily insight report? (y/n): " confirm
    if [[ ! "$confirm" =~ ^[Yy]$ ]]; then
        logit -w "Daily insight report generation cancelled"
        return 0
    fi
    
    # Collect developer's personal description of the day's work
    echo ""
    logit -i "Let's add your perspective to make the insight more meaningful..."
    echo ""
    
    local dev_description=""
    local work_focus=""
    local deliverables=""
    local challenges=""
    local next_steps=""
    
    # Collect developer input
    work_focus=$(input "What was your main focus?")
    # deliverables=$(input "What did you deliver/complete?" --optional)
    # challenges=$(input "Any challenges or blockers encountered?" --optional)
    # next_steps=$(input "What are your next steps/plans?" --optional)
    
    # Combine all developer input
    if [ -n "$work_focus" ] || [ -n "$deliverables" ] || [ -n "$challenges" ] || [ -n "$next_steps" ]; then
        dev_description="
=== DEVELOPER NOTES ===
"
        if [ -n "$work_focus" ]; then
            dev_description+="
MAIN FOCUS: $work_focus"
        fi
        
        if [ -n "$deliverables" ]; then
            dev_description+="
DELIVERABLES: $deliverables"
        fi
        
        if [ -n "$challenges" ]; then
            dev_description+="
CHALLENGES: $challenges"
        fi
        
        if [ -n "$next_steps" ]; then
            dev_description+="
NEXT STEPS: $next_steps"
        fi
        
        dev_description+="
"
    fi
    
    
    # Prepare analysis data with developer perspective
    local analysis_data="$dev_description
=== COMMITS TODAY ===
$all_commits

=== UNCOMMITTED CHANGES ===
$all_changes
"

    # Generate and save the insight report
    sdk_fac_git_cmd_generate_insight_report "$analysis_data" "$cache_file" "$total_files_changed" "$total_insertions" "$total_deletions"
}

