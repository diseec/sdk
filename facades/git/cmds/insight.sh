#!/bin/bash

# Unified git command wrapper
_git_cmd() {
    local module_path="$1"
    local repo_path="$2"
    shift 2
    
    if [ "$module_path" = "." ]; then
        cd "$repo_path" && cli_ctx git _ "$@" 2>/dev/null
    else
        cd "$repo_path" && git "$@" 2>/dev/null
    fi
}

# Get today's date components
_get_today() {
    local format="$1"
    case "$format" in
        "start") date '+%Y-%m-%d 00:00:00' ;;
        "end") date '+%Y-%m-%d %H:%M:%S' ;;
        "date") date '+%Y-%m-%d' ;;
    esac
}

# Check cache and return action
_check_cache() {
    local cache_file="$1"
    local today_date="$(_get_today date)"
    
    if [ -f "$cache_file" ]; then
        if confirm "Found insight for today $today_date. rewrite?"; then
            return 1  # rewrite
        else
            echo -e "\033[36m$(cat "$cache_file")\033[0m"
            return 0  # use cached
        fi
    fi
    return 2  # generate new
}

# Get today's commits for a repository
_get_repo_commits() {
    local module_name="$1"
    local module_path="$2"
    local repo_path="$D_CTX_DIR/$module_path"
    
    [ ! -d "$repo_path/.git" ] && [ ! -f "$repo_path/.git" ] && return
    
    local today_start="$(_get_today start)"
    local today_end="$(_get_today end)"
    
    _git_cmd "$module_path" "$repo_path" log \
        --since="$today_start" --until="$today_end" \
        --pretty=format:"%h|%s|%an|%ad" --date=short | \
    while IFS='|' read -r hash subject author date; do
        [ -n "$hash" ] || continue
        
        # Get filtered commit diff
        local diff=$(_git_cmd "$module_path" "$repo_path" show --stat "$hash" | _filter_large_files "$repo_path")
        
        cat << EOF
REPO: $module_name
COMMIT: "$hash" - $subject
AUTHOR: $author
DATE: $date
CHANGES:
$diff
--- \n
EOF
    done
}

# Get uncommitted changes for a repository
_get_repo_changes() {
    local module_name="$1"
    local module_path="$2"
    local repo_path="$D_CTX_DIR/$module_path"
    
    [ ! -d "$repo_path/.git" ] && [ ! -f "$repo_path/.git" ] && return
    
    local status=$(_git_cmd "$module_path" "$repo_path" status --porcelain | _filter_large_files "$repo_path")
    [ -z "$status" ] && return
    
    local staged=$(_git_cmd "$module_path" "$repo_path" diff --staged)
    local unstaged=$(_git_cmd "$module_path" "$repo_path" diff)
    
    cat << EOF
REPO: $module_name - UNCOMMITTED CHANGES
STATUS:
$status
EOF
    
    [ -n "$staged" ] && cat << EOF
STAGED CHANGES:
$staged
EOF
    
    [ -n "$unstaged" ] && cat << EOF
UNSTAGED CHANGES:
$unstaged
EOF
    
    echo "---"
}

# Filter out large auto-generated files
_filter_large_files() {
    local repo_path="$1"
    while IFS= read -r line; do
        local file=$(echo "$line" | grep '|' | sed 's/|.*$//' | sed 's/^ *//')
        if [ -n "$file" ] && [ -f "$repo_path/$file" ] && 
           cli_ctx ai function sdk_fac_ai_is_large_autogenerated_file "$repo_path/$file"; then
            continue
        fi
        echo "$line"
    done
}

# Get repository statistics
_get_repo_stats() {
    local module_path="$1"
    local repo_path="$D_CTX_DIR/$module_path"
    
    [ ! -d "$repo_path/.git" ] && [ ! -f "$repo_path/.git" ] && return
    
    local today_start="$(_get_today start)"
    local today_end="$(_get_today end)"
    
    _git_cmd "$module_path" "$repo_path" log \
        --since="$today_start" --until="$today_end" --numstat | \
    awk '/^[0-9]+\t[0-9]+\t/ { files++; add+=$1; del+=$2 } END { print files+0, add+0, del+0 }'
}

# Generate commit summary for display
_get_commit_summary() {
    local module_name="$1"
    local module_path="$2"
    local repo_path="$D_CTX_DIR/$module_path"
    
    [ ! -d "$repo_path/.git" ] && [ ! -f "$repo_path/.git" ] && return
    
    local today_start="$(_get_today start)"
    local today_end="$(_get_today end)"
    
    _git_cmd "$module_path" "$repo_path" log \
        --since="$today_start" --until="$today_end" \
        --pretty=format:"$module_name|%h|%s|%an|%ad" --date=short
}

# Display commit table
_display_commits() {
    local commit_data="$1"
    local stats="$2"
    
    echo "The following commits will be included in the daily insight:"
    echo
    printf "%-15s %-8s %-50s %-20s %-10s\n" "REPOSITORY" "COMMIT" "MESSAGE" "AUTHOR" "DATE"
    printf "%s\n" "$(printf '=%.0s' {1..110})"
    
    echo "$commit_data" | while IFS='|' read -r repo hash message author date; do
        [ -n "$hash" ] || continue
        # Truncate long messages
        [ ${#message} -gt 47 ] && message="${message:0:44}..."
        printf "%-15s %-8s %-50s %-20s %-10s\n" "$repo" "$hash" "$message" "$author" "$date"
    done
    
    echo
    echo "Total changes: $stats"
    echo
}

# Show preview of analysis data and get confirmation
_show_analysis_preview() {
    local work_focus="$1"
    local all_commits="$2"
    local all_changes="$3"
    
    echo
    echo -e "\033[97mPreview of data to be analyzed:\033[0m"
    echo -e "\033[97m================================\033[0m"
    
    # Show developer notes section
    echo -e "\033[97m=== DEVELOPER NOTES ===\033[0m"
    echo -e "\033[90m$work_focus\033[0m"
    echo
    
    # Show commits preview
    if [ -n "$all_commits" ]; then
        local commits_lines=$(echo "$all_commits" | wc -l | tr -d ' ')
        echo -e "\033[97m=== COMMITS TODAY === ($commits_lines lines)\033[0m"
        echo -e "\033[90m$(echo "$all_commits" | head -20)\033[0m"
        if [ "$commits_lines" -gt 20 ]; then
            echo -e "\033[2;90m... [truncated $(($commits_lines - 20)) more lines]\033[0m"
        fi
    else
        echo -e "\033[97m=== COMMITS TODAY === (0 lines)\033[0m"
        echo -e "\033[90mNo commits found for today\033[0m"
    fi
    echo
    
    # Show changes preview
    if [ -n "$all_changes" ]; then
        local changes_lines=$(echo "$all_changes" | wc -l | tr -d ' ')
        echo -e "\033[97m=== UNCOMMITTED CHANGES === ($changes_lines lines)\033[0m"
        echo -e "\033[90m$(echo "$all_changes" | head -5)\033[0m"
        if [ "$changes_lines" -gt 5 ]; then
            echo -e "\033[2;90m... [truncated $(($changes_lines - 5)) more lines]\033[0m"
        fi
    else
        echo -e "\033[97m=== UNCOMMITTED CHANGES === (0 lines)\033[0m"
        echo -e "\033[90mNo uncommitted changes found\033[0m"
    fi
    echo
    
    # Get confirmation
    confirm "Proceed with AI analysis of this data?"
}

# Generate and save insight report
_generate_report() {
    local analysis_data="$1"
    local cache_file="$2"
    local stats="$3"
    
    if ! cli_ctx ai function sdk_fac_ai_is_available; then
        stdout -e "AI not available. Showing raw data instead."
        echo "$analysis_data"
        return
    fi
    
    stdout -a --processing "Writing daily insights"
    
    local temp_file=$(mktemp)
    echo "$analysis_data" > "$temp_file"

    processing_start "AI_WRITING" ai_insight
    local ai_insight=$(cli_ctx ai generate insight "$temp_file")
    processing_stop ai_insight
    rm -f "$temp_file"
    
    if [ -n "$ai_insight" ]; then
        cat << EOF > "$cache_file"
Daily Development Report - $(_get_today date)

$ai_insight

$stats
EOF
        echo "Daily insight report generated and cached"
        echo
        echo -e "\033[36m$(cat "$cache_file")\033[0m"
    else
        stdout -e "Failed to generate AI insight. Showing raw data."
        echo "$analysis_data"
    fi
    echo
}

# Main daily insight function
sdk_fac_git_cmd_daily_insight() {
    local today_date="$(_get_today date)"
    local cache_dir=$(cli_ctx config function sdk_fac_con_get_cache_subdir repository "insights")
    local cache_file="$cache_dir/daily_insight_$today_date.txt"

    # Check cache
    _check_cache "$cache_file"
    case $? in
        0) return 0 ;;  # use cached
        1) ;;           # rewrite
        2) ;;           # generate new
    esac
    
    echo "Preparing daily insight report for $(_get_today start) to $(_get_today end).."
    
    # Collect all repository data
    local all_commits=""
    local all_changes=""
    local all_summaries=""
    local total_stats="0 0 0"  # files additions deletions
    
    # Process repositories
    _process_repo() {
        local module_name="$1"
        local module_path="$2"
        
        # Collect commits
        local commits=$(_get_repo_commits "$module_name" "$module_path")
        [ -n "$commits" ] && all_commits+="$commits"
        
        # Collect changes
        local changes=$(_get_repo_changes "$module_name" "$module_path")
        [ -n "$changes" ] && all_changes+="$changes"
        
        # Collect summary for display
        local summary=$(_get_commit_summary "$module_name" "$module_path")
        [ -n "$summary" ] && all_summaries+="$summary"$'\n'
        
        # Collect stats
        local stats=$(_get_repo_stats "$module_path")
        if [ "$stats" != "0 0 0" ]; then
            local files=$(echo $total_stats | cut -d' ' -f1)
            local adds=$(echo $total_stats | cut -d' ' -f2)
            local dels=$(echo $total_stats | cut -d' ' -f3)
            local new_files=$(echo $stats | cut -d' ' -f1)
            local new_adds=$(echo $stats | cut -d' ' -f2)
            local new_dels=$(echo $stats | cut -d' ' -f3)
            total_stats="$((files + new_files)) $((adds + new_adds)) $((dels + new_dels))"
        fi
    }
    
    # Process main repository and submodules
    _process_repo "$D_REPO_NAME" "."
    cli_ctx submodule foreach_active _process_repo
    
    # Check if any data was collected
    if [ -z "$all_commits" ] && [ -z "$all_changes" ]; then
        stdout -i "No commits or changes found for today"
        return 0
    fi
    
    # Format stats for display
    local files=$(echo "$total_stats" | cut -d' ' -f1)
    local adds=$(echo "$total_stats" | cut -d' ' -f2)
    local dels=$(echo "$total_stats" | cut -d' ' -f3)
    
    local stats_display=""
    if [ "$files" -gt 0 ]; then
        stats_display="$files files, +$adds -$dels lines"
    else
        stats_display="No changes"
    fi
    
    # Display commit summary and confirm
    _display_commits "$all_summaries" "$stats_display"

    echo
    stdout -i --processing "Let's add your perspective to make the insight more meaningful"
    echo
    
    stdin work_focus "What was your main focus?"
    
    # Show preview and get confirmation
    if ! _show_analysis_preview "$work_focus" "$all_commits" "$all_changes"; then
        stdout -i "Daily insight generation cancelled"
        return 0
    fi
    
    # Prepare analysis data
    local analysis_data="
=== DEVELOPER NOTES ===
MAIN FOCUS: $work_focus

=== COMMITS TODAY ===
$all_commits

=== UNCOMMITTED CHANGES ===
$all_changes
"

    # Generate and save report
    _generate_report "$analysis_data" "$cache_file" "$stats_display"
}

