export DISEEC_WORKSPACE_DIR="$HOME/diseec"

rootdir() {
  local dir="$(pwd)"
  while [ "$dir" != "/" ]; do
    if [ -f "$dir/cli" ]; then
      echo "$dir"
      return 0
    fi
    dir="$(dirname "$dir")"
  done
  echo "Error: Could not find project root containing 'cli' file" >&2
  return 1
}
if [ -z "$ROOT_DIR" ]; then export ROOT_DIR="$(rootdir)"; fi

export CLI_SRC="$ROOT_DIR/node_modules/@diseec/devops"

export VERSION=$(grep '"version"' $CLI_SRC/package.json | head -1 | sed -E 's/.*"version": *"([^"]+)".*/\1/')

# Extract repository URL from .git/config or submodule gitdir without using git command
GIT_DIR="$ROOT_DIR/.git"
GIT_CONFIG_FILE=""
REPO_URL=""
if [ -d "$GIT_DIR" ]; then
  # Standard git repo
  GIT_CONFIG_FILE="$GIT_DIR/config"
elif [ -f "$GIT_DIR" ]; then
  # Submodule or worktree: .git is a file pointing to actual gitdir
  GITDIR_PATH=$ROOT_DIR/$(awk -F': ' '/^gitdir:/ {print $2}' "$GIT_DIR")
  if [ -n "$GITDIR_PATH" ] && [ -f "$GITDIR_PATH/config" ]; then
    GIT_CONFIG_FILE="$GITDIR_PATH/config"
  fi
fi
if [ -f "$GIT_CONFIG_FILE" ]; then
  REPO_URL=$(awk -F' = ' '/\[remote "origin"\]/ {found=1} found && /url =/ {print $2; exit}' "$GIT_CONFIG_FILE")
fi
# Extract repo name from URL (supports SSH and HTTPS)
REPO_NAME=""
if [ -n "$REPO_URL" ]; then
  # Remove trailing .git if present
  REPO_NAME=$(basename "${REPO_URL%.git}")
fi
export REPO_NAME

get_projects_dir() {
  DISEEC_PROJECTS_DIR="$DISEEC_WORKSPACE_DIR/projects"
  if [ ! -d "$DISEEC_PROJECTS_DIR" ]; then
    mkdir -p "$DISEEC_PROJECTS_DIR"
  fi
  # Return the projects directory
  echo "$DISEEC_PROJECTS_DIR"
}
export DISEEC_PROJECTS_DIR=$(get_projects_dir)

get_cache_dir() {
  DISEEC_CACHE_DIR="$DISEEC_WORKSPACE_DIR/.cache"
  if [ ! -d "$DISEEC_CACHE_DIR" ]; then
    mkdir -p "$DISEEC_CACHE_DIR"
  fi
  # Return the cache directory
  echo "$DISEEC_CACHE_DIR"
}
export DISEEC_CACHE_DIR=$(get_cache_dir)

